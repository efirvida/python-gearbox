"""Figures of the README: FEM meshes and FEM results against the standards.

Needs gmsh, matplotlib, Pillow, CalculiX (``ccx`` on the PATH or ``GEARBOX_CCX``) and a display
for the 3D renders of :mod:`render_3d`. Run from the repository root::

    python docs/figures/make_figures.py              # everything
    python docs/figures/make_figures.py meshes       # only the mesh figures (seconds)
    python docs/figures/make_figures.py animations   # only the GIFs (about an hour)

The PNG files are written next to this script. The models are solved in ``docs/figures/work``,
which is not kept. The comparisons are illustrations: the FEM is linear elastic, frictionless and
plane strain (2D), while every standard adds its own simplifications.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import warnings
from math import pi, sin, sqrt
from pathlib import Path

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from gearbox import Gear, Lubricant, Material, MaterialType, Tool, Transmission  # noqa: E402
from gearbox.export.exporters import _build_wheel  # noqa: E402
from gearbox.fem import ToothMeshSettings, mesh_gear, mesh_pair  # noqa: E402
from gearbox.fem._mesh_io import read_mesh  # noqa: E402
from gearbox.fem.post import (  # noqa: E402
    LineOfAction,
    SweepPoint,
    contact_sweep,
    plot_field,
    plot_line_of_action,
    plot_mesh,
)
from gearbox.standards import agma2101, iso6336  # noqa: E402
from gearbox.standards.iso6336 import bending as iso_bending  # noqa: E402

HERE = Path(__file__).parent
WORK = HERE / "work"
CACHE = HERE / "cache"  # solved positions of the animations, see solve_cycle
FORCE = 8000.0  # nominal tangential force [N]
FRAMES = 18  # positions along the path of contact
GIF_SIZE, GIF_DPI = (16, 9), 120  # 1920 x 1080 pixels
GIF_STYLE = {
    "font.size": 12,
    "axes.titlesize": 14,
    "axes.labelsize": 13,
    "xtick.labelsize": 11,
    "ytick.labelsize": 11,
    "legend.fontsize": 11,
}

tool = Tool(
    addendum_coefficient=1.0, dedendum_coefficient=1.25, root_fillet_radius_coefficient=0.38
)
steel = Material(
    material_type=MaterialType.NITROCARBURIZED_STEEL,
    contact_stress_limit=1500.0,
    bending_stress_limit=460.0,
    brinell_hardness=286.7,
)


def gear(teeth: int, shaft: float, helix: float = 0.0) -> Gear:
    return Gear(
        tool=tool,
        material=steel,
        number_of_teeth=teeth,
        module=2.5,
        face_width=34.0,
        helix_angle=helix,
        quality_grade=6,
        surface_roughness=3.67,
        shaft_diameter=shaft,
        shaft_arrangement=3,
        bearing_span=60.0,
        offset=15.0,
    )


def transmission(helix: float = 0.0) -> Transmission:
    # x1 = x2 = 0: the pitch point lies in the single pair contact zone
    return Transmission(
        pinion=gear(22, 35.0, helix),
        wheel=gear(40, 50.0, helix),
        lubricant=Lubricant(kinematic_viscosity_40c=160),
        pinion_speed_rpm=1450.0,
        power_kw=40.0,
        design_life_hours=10_000.0,
    )


# -- drawing helpers ---------------------------------------------------------------------------


def draw_mesh(ax, mesh, linewidth: float = 0.25) -> None:
    plot_mesh(ax, mesh, linewidth)
    ax.set_xticks([])
    ax.set_yticks([])


def figure_gear_meshes() -> None:
    """2D sector of a spur pinion and the 3D mesh of a helical one (rendered by render_3d.py)."""
    flat = mesh_gear(gear(22, 35.0), WORK, "gear_2d", "2D", teeth=3)
    mesh_gear(
        gear(22, 35.0, helix=15.0),
        WORK,
        "gear_3d",
        "3D",
        ToothMeshSettings(flank_size=0.25, tooth_elements=6, width_elements=10),
        teeth=3,
    )
    fig, (left, right) = plt.subplots(1, 2, figsize=(12, 5))
    mesh = read_mesh(flat.paths["msh"])
    draw_mesh(left, mesh)
    left.set_title(f"2D sector, {flat.element_count} quadrilaterals")
    draw_mesh(right, mesh, 0.4)
    right.set_xlim(-6.5, -1.5)
    right.set_ylim(23.5, 27.5)
    right.set_title("root fillet generated by the hob")
    fig.tight_layout()
    fig.savefig(HERE / "mesh_gear.png", dpi=100)
    plt.close(fig)


def figure_mesh_variants() -> None:
    """The two block layouts on a tooth without correction and on a markedly undercut one."""
    cases = [
        ("z = 22, x = 0: no undercut", gear(22, 10.0)),
        ("z = 9, x = 0: marked undercut", gear(9, 10.0)),
    ]
    variants = [
        ("fillet_block", "variant 'fillet_block' (default): own block for the fillet"),
        ("standard", "variant 'standard': root and fillet in one block"),
    ]
    fig, axes = plt.subplots(2, 2, figsize=(12, 10.5))
    warnings.filterwarnings("ignore", "undercutting occurs")  # z = 9 is undercut on purpose
    for row, (label, case) in enumerate(cases):
        data = _build_wheel(case).data
        for column, (variant, title) in enumerate(variants):
            settings = ToothMeshSettings(variant=variant, bore_diameter=0.55 * data["d_f"])
            result = mesh_gear(case, WORK, f"variant_{row}_{column}", "2D", settings, teeth=1)
            ax = axes[row, column]
            draw_mesh(ax, read_mesh(result.paths["msh"]), 0.35)
            angle = np.linspace(-pi / 2 - 0.6, -pi / 2 + 0.6, 200) + pi
            for diameter, style, name in (
                (data["d_b"], "--", "base circle"),
                (data["d_Ff"], ":", "root form circle"),
            ):
                ax.plot(
                    diameter / 2 * np.cos(angle),
                    diameter / 2 * np.sin(angle),
                    style,
                    color="#c0392b",
                    linewidth=1.0,
                    label=name,
                )
            module = case.module
            half = 1.05 * data["d_a"] / 2 * sin(pi / data["z"])
            ax.set_xlim(-half, half)
            ax.set_ylim(data["d_f"] / 2 - 1.4 * module, data["d_a"] / 2 + 0.2 * module)
            ax.set_title(f"{label}\n{title}, {result.element_count} quads", fontsize=10)
            if row == column == 0:
                ax.legend(frameon=False, fontsize=8, loc="lower left")
    fig.tight_layout()
    fig.savefig(HERE / "mesh_variants.png", dpi=100)
    plt.close(fig)


def figure_pair_meshes() -> None:
    """2D pair in mesh and the 3D mesh of a helical pair (rendered by render_3d.py)."""
    flat = mesh_pair(transmission(), WORK, "pair_2d", "2D")
    mesh_pair(
        transmission(15.0),
        WORK,
        "pair_3d",
        "3D",
        ToothMeshSettings(flank_size=0.3, tooth_elements=6, width_elements=10),
        teeth=(3, 4),
    )
    fig, (left, right) = plt.subplots(1, 2, figsize=(12, 6))
    mesh = read_mesh(flat.paths["msh"])
    draw_mesh(left, mesh, 0.2)
    left.set_title(f"2D pair, {flat.element_count} quadrilaterals")
    draw_mesh(right, mesh, 0.4)
    right.set_xlim(-4.5, 4.5)
    right.set_ylim(24.0, 31.0)
    right.set_title("teeth in mesh, zero backlash")
    fig.tight_layout()
    fig.savefig(HERE / "mesh_pair.png", dpi=100)
    plt.close(fig)


def solve_cycle(frames: int) -> tuple[Transmission, LineOfAction, list[SweepPoint]]:
    """Solve the contact at ``frames`` positions of a pinion tooth along the path of contact.

    The solved positions are cached in ``CACHE`` by :func:`gearbox.fem.post.contact_sweep`, so
    the animations can be redrawn without solving again.
    """
    t = transmission()
    line = LineOfAction.of(t)
    margin = 0.15  # mm; keeps clear of the tip corners at the ends of the path
    positions = np.linspace(-line.approach + margin, line.recess - margin, frames)

    def report(index: int, count: int, point: SweepPoint) -> None:
        print(f"frame {index + 1}/{count}: position {point.position:+.2f} mm", flush=True)

    points = contact_sweep(t, CACHE, positions, FORCE, progress=report)
    return t, line, points


def axis_limits(line: LineOfAction) -> tuple[float, float]:
    """Positions shown in the plots: the path of contact A-E and 0.4 mm on either side."""
    return -line.approach - 0.4, line.recess + 0.4


def shade_double_contact(ax, line: LineOfAction) -> None:
    for start, end in line.double_contact_zones():
        ax.axvspan(start, end, color="0.9", zorder=0)
    for name, position in line.points().items():
        if name in "ABCDE":
            ax.axvline(position, color="0.6", linewidth=0.8, linestyle=":")
            ax.text(position, 1.0, name, transform=ax.get_xaxis_transform(), ha="center",
                    va="bottom", fontsize=12, fontweight="bold")  # fmt: skip


def colorbar(fig, ax, contour, label: str) -> None:
    bar = fig.colorbar(contour, ax=ax, location="bottom", fraction=0.04, pad=0.02, aspect=40)
    bar.set_label(label)
    bar.locator = matplotlib.ticker.MaxNLocator(8)
    bar.update_ticks()


def others(point: SweepPoint) -> list[tuple[float, float]]:
    return [patch.point for patch in point.patches if patch is not point.followed]


def save_gif(figures: list, name: str) -> None:
    from io import BytesIO

    from PIL import Image

    images = []
    for fig in figures:
        buffer = BytesIO()
        fig.savefig(buffer, format="png", dpi=GIF_DPI)
        plt.close(fig)
        buffer.seek(0)
        images.append(Image.open(buffer).convert("P", palette=Image.ADAPTIVE, colors=256))
    images[0].save(
        HERE / name, save_all=True, append_images=images[1:], duration=350, loop=0, optimize=True
    )


@plt.rc_context(GIF_STYLE)
def bending_animation(t: Transmission, line: LineOfAction, points: list[SweepPoint]) -> None:
    p, w = t.pinion, t.wheel
    nominal = FORCE / (p.face_width * p.module)
    references = {}
    for gear_, label in ((p, "pinion"), (w, "wheel")):
        root = iso_bending._tooth_root_geometry(t, gear_)
        form = iso_bending._form_factor(t, root)
        correction = iso_bending._stress_correction_factor(root, gear_)
        references[label] = (nominal * form * correction, nominal * form)
    agma = agma2101.calculate_bending(t)
    agma_values = {
        "pinion": nominal / agma.bending_geometry_factor_pinion,
        "wheel": nominal / agma.bending_geometry_factor_wheel,
    }
    positions = [point.position for point in points]
    roots = {
        "pinion": [point.root_stress_pinion for point in points],
        "wheel": [point.root_stress_wheel for point in points],
    }
    top = 1.15 * max(max(roots["pinion"]), max(roots["wheel"]), *agma_values.values())
    colours = {"pinion": "#c0392b", "wheel": "#2e6da4"}
    figures = []
    for index, point in enumerate(points):
        fig, (left, right) = plt.subplots(1, 2, figsize=GIF_SIZE, width_ratios=(1.25, 1))
        contour = plot_field(left, point.stress("principal"), vmax=0.9 * top, edges=False)
        colorbar(fig, left, contour, "first principal stress [MPa]")
        left.set_xlim(-10.5, 10.5)
        left.set_ylim(19.5, 37.0)
        plot_line_of_action(left, line, point.followed.point, others=others(point))
        left.set_xticks([])
        left.set_yticks([])
        left.set_title("first principal stress; magenta: path of contact A-E")
        shade_double_contact(right, line)
        for label in ("pinion", "wheel"):
            colour = colours[label]
            right.plot(positions[: index + 1], roots[label][: index + 1], "o-", color=colour,
                       label=f"FEM {label}", markersize=5)  # fmt: skip
            iso, beam = references[label]
            right.axhline(iso, color=colour, linestyle="--", linewidth=1,
                          label=f"ISO 6336-3 Y_F Y_S ({label})")  # fmt: skip
            right.axhline(agma_values[label], color=colour, linestyle="-.", linewidth=1,
                          label=f"AGMA 908 1/J ({label})")  # fmt: skip
            right.axhline(beam, color=colour, linestyle=":", linewidth=1,
                          label=f"cantilever Y_F ({label})")  # fmt: skip
        right.set_xlim(*axis_limits(line))
        right.set_ylim(0, top)
        right.set_xlabel("contact position on the line of action [mm] (0 = pitch point)")
        right.set_ylabel("tooth root stress [MPa]")
        right.legend(frameon=False, ncol=2, loc="lower left")
        right.spines[["top", "right"]].set_visible(False)
        right.set_title(
            f"spur z = 22/40, m = 2.5, Ft = {FORCE:.0f} N, b = 34 mm; grey: two pairs", pad=24
        )
        fig.tight_layout()
        figures.append(fig)
    save_gif(figures, "bending.gif")


@plt.rc_context(GIF_STYLE)
def contact_animation(t: Transmission, line: LineOfAction, points: list[SweepPoint]) -> None:
    p, w = t.pinion, t.wheel
    load = points[0].requested_torque / line.base_radii[0]  # normal load per unit width
    iso = iso6336.calculate_pitting(t)
    ratio = w.number_of_teeth / p.number_of_teeth
    nominal = sqrt(FORCE / (p.reference_diameter * p.face_width) * (ratio + 1) / ratio)
    agma = agma2101.calculate_pitting(t)
    agma_stress = agma.elastic_coefficient * sqrt(
        FORCE / (p.reference_diameter * t.net_face_width * agma.pitting_geometry_factor)
    )
    iso_values = {
        "ISO 6336-2 Z_H Z_E": iso.zone_factor * iso.elasticity_factor * nominal,
        "ISO 6336-2 Z_H Z_E Z_eps": iso.zone_factor
        * iso.elasticity_factor
        * iso.contact_ratio_factor
        * nominal,
    }
    positions = [point.position for point in points]
    pressures = [point.followed.pressure for point in points]
    path = np.linspace(-line.approach, line.recess, 300)
    hertz = line.hertz_pressure(path, load)
    top = 1.3 * hertz.max()  # tip edge contacts are singular and drawn at the top
    figures = []
    for index, point in enumerate(points):
        fig, (left, right) = plt.subplots(1, 2, figsize=GIF_SIZE, width_ratios=(1.25, 1))
        # the von Mises stress peaks under the surface at about 0.6 times the contact pressure
        contour = plot_field(left, point.stress("von_mises"), vmax=0.65 * hertz.max(),
                             edge_width=0.4)  # fmt: skip
        colorbar(fig, left, contour, "von Mises stress [MPa]")
        x, y = point.followed.point
        left.set_xlim(x - 1.0, x + 1.0)
        left.set_ylim(y - 1.0, y + 1.0)
        plot_line_of_action(left, line, point.followed.point, labels=False, others=others(point))
        left.set_xticks([])
        left.set_yticks([])
        left.set_title("von Mises stress at the followed contact (2 mm window)")
        shade_double_contact(right, line)
        right.plot(path, hertz, "k--", linewidth=1, label="Hertz, whole load on one pair")
        for number, (start, end) in enumerate(line.double_contact_zones()):
            shared = np.linspace(start, end, 100)
            right.plot(shared, line.hertz_pressure(shared, load / 2), "k:", linewidth=1.2,
                       label="Hertz, load shared by two pairs" if number == 0 else None)  # fmt: skip
        for (label, value), style in zip(iso_values.items(), ("-.", ":"), strict=True):
            right.axhline(value, color="#2e6da4", linestyle=style, linewidth=1, label=label)
        right.axhline(agma_stress, color="#27ae60", linestyle="-.", linewidth=1,
                      label="AGMA 2001 C_p, I")  # fmt: skip
        right.plot(positions[: index + 1], pressures[: index + 1], "o-", color="#c0392b",
                   markersize=5, label="FEM, followed pair")  # fmt: skip
        seen = [
            patch
            for done in points[: index + 1]
            for patch in done.patches
            if patch is not done.followed
        ]
        flank = [patch for patch in seen if patch.on_path]
        right.plot([patch.position for patch in flank], [patch.pressure for patch in flank],
                   "o", color="#c0392b", markerfacecolor="white", markersize=6,
                   label="FEM, the other pair in contact")  # fmt: skip
        edges = [patch for patch in seen if not patch.on_path]
        if edges:
            low, high = axis_limits(line)
            where = [np.clip(patch.position, low + 0.05, high - 0.05) for patch in edges]
            right.plot(where, [0.96 * top] * len(edges), "^", color="#8e44ad", markersize=10,
                       label="FEM, tip edge contact outside A-E (off scale)")  # fmt: skip
            peak = max(patch.pressure for patch in edges)
            right.text(0.5, 0.97, f"sharp tip edge contacts: up to {peak:.0f} MPa",
                       transform=right.transAxes, ha="center", va="top",
                       color="#8e44ad")  # fmt: skip
        right.set_xlim(*axis_limits(line))
        right.set_ylim(0, top)
        right.set_xlabel("contact position on the line of action [mm] (0 = pitch point)")
        right.set_ylabel("contact stress [MPa]")
        right.legend(frameon=False, loc="lower left")
        right.spines[["top", "right"]].set_visible(False)
        right.set_title(
            f"spur z = 22/40, m = 2.5, Ft = {FORCE:.0f} N, b = 34 mm; grey: two pairs", pad=24
        )
        fig.tight_layout()
        figures.append(fig)
    save_gif(figures, "contact.gif")


def main(parts: list[str]) -> None:
    """Make the ``meshes`` figures, the ``animations`` or both (no argument)."""
    parts = parts or ["meshes", "animations"]
    WORK.mkdir(exist_ok=True)
    try:
        if "meshes" in parts:
            figure_gear_meshes()
            figure_mesh_variants()
            figure_pair_meshes()
            # one process per image: Gmsh's FLTK window cannot be opened twice in one process
            subprocess.run([sys.executable, str(HERE / "render_3d.py")], check=True)
        if "animations" in parts:
            t, path, frames = solve_cycle(FRAMES)
            bending_animation(t, path, frames)
            contact_animation(t, path, frames)
    finally:
        shutil.rmtree(WORK, ignore_errors=True)


if __name__ == "__main__":
    main(sys.argv[1:])
